/**
 * @file coach-notification-toast.js
 * @description Presentational UI component that listens for notification creation events and displays transient toast alerts.
 * @module Coach/Notification/Toast
 */

import { CoachEventBus } from '../coach-event-bus.js';

export const CoachNotificationToast = {
    containerElement: null,

    initialize() {
        this.ensureContainer();
        this.registerEventListeners();
        return true;
    },

    ensureContainer() {
        if (this.containerElement && document.body.contains(this.containerElement)) {
            return this.containerElement;
        }

        const container = document.createElement('div');
        container.id = 'coach-toast-container';
        container.className = 'toast-container position-fixed bottom-0 end-0 p-3';
        container.style.zIndex = '1080';
        document.body.appendChild(container);
        this.containerElement = container;
        return container;
    },

    registerEventListeners() {
        // Listen to new notification events generated by the engine/events bridge
        CoachEventBus.on('coach:notification:created', (notification) => {
            this.show(notification);
        });
    },

    show(notification) {
        if (!notification) return;

        const container = this.ensureContainer();
        const toastId = 'toast_' + Date.now() + '_' + Math.floor(Math.random() * 1000);

        let bgClass = 'bg-primary text-white';
        let icon = 'ℹ️';

        switch (notification.type) {
            case 'success':
                bgClass = 'bg-success text-white';
                icon = '✅';
                break;
            case 'achievement':
                bgClass = 'bg-warning text-dark';
                icon = '🏆';
                break;
            case 'reminder':
                bgClass = 'bg-info text-dark';
                icon = '⏰';
                break;
            case 'info':
            default:
                bgClass = 'bg-dark text-white';
                icon = '📢';
                break;
        }

        const toastHtml = `
            <div id="${toastId}" class="toast align-items-center ${bgClass} border-0 shadow mb-2" role="alert" aria-live="assertive" aria-atomic="true">
                <div class="d-flex">
                    <div class="toast-body d-flex align-items-center">
                        <span class="me-2 fs-5">${icon}</span>
                        <div>
                            <strong class="d-block mb-1">${notification.title || 'Notifikasi'}</strong>
                            <span class="small">${notification.message || ''}</span>
                        </div>
                    </div>
                    <button type="button" class="btn-close btn-close-white me-2 m-auto" data-bs-dismiss="toast" aria-label="Close"></button>
                </div>
            </div>
        `;

        container.insertAdjacentHTML('beforeend', toastHtml);

        const toastElement = document.getElementById(toastId);
        if (toastElement) {
            // Auto-dismiss after 4 seconds
            setTimeout(() => {
                toastElement.classList.remove('show');
                setTimeout(() => toastElement.remove(), 300);
            }, 4000);

            // Manual close binding if Bootstrap JS/events are available
            const closeBtn = toastElement.querySelector('.btn-close');
            if (closeBtn) {
                closeBtn.addEventListener('click', () => {
                    toastElement.remove();
                });
            }
        }
    }
};